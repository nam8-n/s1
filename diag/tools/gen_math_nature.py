def fmt(v, u=""):
    v = round(v, 6)
    s = f"{int(v):,}" if float(v).is_integer() else f"{v:,}".rstrip("0")
    return s + (" " + u if u and u[0].isascii() and u[0].isalpha() else u)

def num(d, lv, q, val, unit, dis, ctx=None):
    opts = sorted(set([val] + dis))
    assert len(opts) == 5 and val in opts, (q, opts)
    return dict(d=d, lv=lv, c=ctx, q=q, o=[fmt(x, unit) for x in opts], a=opts.index(val), key=fmt(val, unit))

def txt(d, lv, q, opts, correct, ctx=None):
    assert len(opts) == 5 and correct in opts
    return dict(d=d, lv=lv, c=ctx, q=q, o=opts, a=opts.index(correct), key=correct)

